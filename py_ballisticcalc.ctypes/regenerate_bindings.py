#!/usr/bin/env python
"""Regenerate py_ballisticcalc_ctypes/_native_gen.py, the ctypes bindings of bclibc_ffi.h.

ctypesgen is a development dependency (``uv sync --group dev``); the generated file is committed, so building the package
does not need it, nor a C preprocessor. Run this after the bclibc submodule is bumped and commit the result; the test
``tests/test_bindings.py`` fails when the file is out of date.

    python regenerate_bindings.py [--check]

``--check`` writes nothing: it exits non-zero when the committed file differs from what the current header gives.
"""

import difflib
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import _bclibc  # noqa: E402

STUBS = HERE / "ctypesgen_stubs"
OUT = HERE / "py_ballisticcalc_ctypes" / "_native_gen.py"
HEADER_RELATIVE = "include/bclibc/ffi/bclibc_ffi.h"


def _header() -> Path:
    return _bclibc.shared() / HEADER_RELATIVE


def functions(header_text: str) -> set[str]:
    """The BCLIBCFFI_* functions a header (or a generated module) names."""
    return set(re.findall(r"\bBCLIBCFFI_[a-z0-9_]+", header_text))


def generate(destination: Path) -> str:
    """Run ctypesgen into destination; return the text with the machine-dependent header replaced by a stable one."""
    header = _header()
    # the console script of the interpreter's environment (ctypesgen has no __main__)
    script = Path(sys.executable).with_name("ctypesgen")
    command = [
        str(script) if script.exists() else (shutil.which("ctypesgen") or "ctypesgen"),
        "-I", str(STUBS),
        "-D", "BCLIBC_API=",  # the export macro is not part of the declarations
        str(header),
        "-l", "bclibc_ffi",
        "-o", str(destination),
        "--no-macro-warnings", "--no-embed-preamble",
    ]  # fmt: skip
    done = subprocess.run(command, capture_output=True, text=True)
    if done.returncode != 0:
        sys.exit(f"ctypesgen failed ({done.returncode}):\n{done.stderr}")
    text = destination.read_text()
    # ctypesgen reports a parse error for the __attribute__ export macro and still writes everything; that every function
    # of the header made it into the module is what is checked, not the message
    missing = functions(header.read_text()) - functions(text)
    if missing:
        sys.exit(f"ctypesgen left out {len(missing)} functions of {header.name}: {sorted(missing)[:5]}\n{done.stderr}")
    version = _bclibc.bclibc_version(_bclibc.shared())[0]
    stable = (
        "Generated by regenerate_bindings.py (ctypesgen) from bclibc_ffi.h of bclibc " + version + ".\n\n"
        "ctypesgen -I ctypesgen_stubs -D BCLIBC_API= bclibc_ffi.h -l bclibc_ffi --no-macro-warnings --no-embed-preamble\n"
    )
    return re.sub(r"Generated with:\n.*?\n\n", stable + "\n", text, count=1, flags=re.S)


def main(argv: list[str]) -> int:
    with tempfile.TemporaryDirectory() as tmp:
        new = generate(Path(tmp) / "gen.py")
    if "--check" in argv:
        old = OUT.read_text() if OUT.exists() else ""
        if old == new:
            return 0
        sys.stdout.writelines(
            difflib.unified_diff(old.splitlines(True), new.splitlines(True), "committed", "regenerated", n=1)
        )
        return 1
    OUT.write_text(new)
    print(f"wrote {OUT.relative_to(HERE)}: {len(functions(new))} functions")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
