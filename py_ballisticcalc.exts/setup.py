#!/usr/bin/env python

"""setup.py of py_ballisticcalc.exts: Cython over the C ABI of bclibc, as one extension module.

``py_ballisticcalc_exts/_native.pyx`` declares the C ABI through ``_bcffi.pxd`` (autopxd2 makes it from bclibc_ffi.h, see
``regenerate_bindings.py``). The module is built with the bclibc core and the C ABI wrapper (``src/ffi/bclibc_ffi.cpp``)
compiled into it: no shared library, no ``auditwheel``/``delocate`` repair. Where the Python stable ABI is available (not
free-threaded, Emscripten, Android, iOS) it is an abi3 wheel for CPython 3.11+, as before the C ABI rewrite.

The sources come from the repository's top-level bclibc submodule, or from a staged copy (see ``_bclibc.py``).

Environment variables:
    CC, CXX, CFLAGS, CXXFLAGS, LDFLAGS  toolchain (the module and the core are C++)
    DISABLE_SHARED_STRIP  keep the symbols
    CYTHON_COVERAGE  line tracing of the .pyx (forces a regeneration, and no stable ABI: tracing uses internal CPython APIs)
    CYTHON_SAFETY  bounds, wraparound, initialization, None and overflow checks, no cdivision
    CYTHON_FORCE_REGEN  regenerate the C++ from the .pyx even when it is up to date
"""

import os
import sys
import sysconfig
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import _bclibc
from setuptools import Extension, setup
from setuptools.command.build_ext import build_ext as _build_ext
from setuptools.command.sdist import sdist as _sdist

try:
    from Cython.Build import cythonize
except ImportError:
    cythonize = None

PACKAGE = "py_ballisticcalc_exts"
CORE_NAMES = (
    "base_types",
    "interp",
    "traj_data",
    "traj_filter",
    "engine",
    "euler",
    "rk4",
    "cash_karp",
    "dormand_prince",
    "tsitouras",
    "velocity_verlet",
)


def env_on(name: str) -> bool:
    return os.environ.get(name, "0").lower() in {"1", "true", "yes", "on"}


ENABLE_CYTHON_COVERAGE = env_on("CYTHON_COVERAGE")
ENABLE_CYTHON_SAFETY = env_on("CYTHON_SAFETY")
CYTHON_FORCE_REGEN = env_on("CYTHON_FORCE_REGEN")


_PLATFORM = sysconfig.get_platform()
IS_EMSCRIPTEN = "emscripten" in _PLATFORM
IS_ANDROID = "android" in _PLATFORM or sys.platform == "android" or hasattr(sys, "getandroidapilevel")
IS_IOS = "ios" in _PLATFORM
IS_MACOS = _PLATFORM.startswith("macosx")
IS_MSVC = sys.platform == "win32"
# the policy of this package since its first abi3 release
PY_LIMITED_API_HEX = "0x030B0000"  # CPython 3.11
PY_LIMITED_API_TAG = "cp311"
USE_LIMITED_API = (
    not ENABLE_CYTHON_COVERAGE
    and not bool(sysconfig.get_config_var("Py_GIL_DISABLED"))
    and not IS_EMSCRIPTEN
    and not IS_ANDROID
    and not IS_IOS
)


DIRECTIVES = {
    "language_level": 3,
    "embedsignature": True,
    "cdivision": True,  # use with caution! can affect on "/" operator
    "binding": False,
    "c_api_binop_methods": True,
    "warn.undeclared": False,
    "warn.unreachable": True,
    "warn.maybe_uninitialized": True,
    "warn.unused": False,  # the autogenerated pickle/state code is noisy
    "warn.unused_arg": False,
    "warn.multiple_declarators": True,
    "show_performance_hints": True,
    "freethreading_compatible": True,
}
if ENABLE_CYTHON_COVERAGE:
    DIRECTIVES["linetrace"] = True
if ENABLE_CYTHON_SAFETY:  # correctness checks over speed
    DIRECTIVES.update(
        boundscheck=True, wraparound=True, initializedcheck=True, nonecheck=True, cdivision=False, overflowcheck=True
    )


def flags() -> tuple[list[str], list[str], list[tuple[str, str | None]]]:
    """(compile args, link args, macros) of the C++ module and core."""
    macros: list[tuple[str, str | None]] = [("__CYTHON__", "1")]
    if ENABLE_CYTHON_COVERAGE:  # tracing in both with-GIL and nogil regions
        macros += [("CYTHON_TRACE", "1"), ("CYTHON_TRACE_NOGIL", "1")]
    if USE_LIMITED_API:
        macros.append(("Py_LIMITED_API", PY_LIMITED_API_HEX))
    if IS_MSVC:
        compile_args = ["/O2", "/W3", "/std:c++17", "/EHs-c-", "/GR-"]
        if _PLATFORM.lower().startswith(("win-arm", "win_arm")):
            compile_args.append("/fp:precise")  # MSVC on ARM
        macros += [("BCLIBC_FFI_EXPORT", None), ("_WINDLL", None), ("NOMINMAX", None)]
        return compile_args, [], macros
    # -ffp-contract=off: the results are bit for bit those of the other bclibc bindings
    compile_args = [
        "-O3", "-Wall", "-std=c++17", "-fno-exceptions", "-fno-rtti", "-ffp-contract=off", "-fvisibility=hidden",
        "-ffunction-sections", "-fdata-sections",
    ]  # fmt: skip
    link_args: list[str] = []
    if IS_MACOS or IS_IOS:
        compile_args.append("-stdlib=libc++")
        link_args += ["-stdlib=libc++", "-Wl,-dead_strip", "-Wl,-x"]
        if IS_MACOS:
            os.environ["CC"], os.environ["CXX"] = "clang", "clang++"
    elif IS_EMSCRIPTEN:
        compile_args = [a for a in compile_args if a not in ("-fvisibility=hidden",)]  # wasm-ld: no strip or gc flags
        compile_args += ["-fPIC"]
    else:
        link_args.append("-Wl,--gc-sections")
        if not env_on("DISABLE_SHARED_STRIP"):
            link_args.append("-Wl,-strip-all")
    return compile_args, link_args, macros


def extensions() -> list[Extension]:
    source = _bclibc.bclibc_dir()
    gen = _bclibc.write_version_header(source, HERE / "build" / "gen")
    compile_args, link_args, macros = flags()
    sources = [f"{PACKAGE}/_native.pyx"]
    # setup() takes sources as /-separated paths relative to this directory, also for a submodule outside of it
    src = Path(os.path.relpath(source, HERE)) / "src"
    sources += [(src / f"{name}.cpp").as_posix() for name in CORE_NAMES]
    sources.append((src / "ffi" / "bclibc_ffi.cpp").as_posix())
    ext = Extension(
        f"{PACKAGE}._native",
        sources=sources,
        include_dirs=[str(source / "include"), str(source / "src"), str(gen), PACKAGE],
        language="c++",
        define_macros=macros,
        extra_compile_args=compile_args,
        extra_link_args=link_args,
        py_limited_api=USE_LIMITED_API,
    )
    return cythonize(
        [ext],
        compiler_directives=DIRECTIVES,
        annotate=True,  # the .html annotations
        build_dir="build",  # to keep built data
        force=ENABLE_CYTHON_COVERAGE or CYTHON_FORCE_REGEN,
        nthreads=os.cpu_count() or 1,  # .pyx -> .cpp across CPU cores
    )


class build_ext(_build_ext):
    """Compiles the sources of the one extension across CPU cores (setuptools parallelises only between extensions)."""

    def build_extension(self, ext):
        compiler = self.compiler
        compile_serial = compiler.compile

        def compile_parallel(sources, *args, **kwargs):
            # one source per call, in a thread of its own: a call spawns the compiler and waits; every source has an object
            # file of its own, the order of the objects is that of the sources. MSVC prepares its environment on first use
            if hasattr(compiler, "initialize") and not getattr(compiler, "initialized", True):
                compiler.initialize()
            with ThreadPoolExecutor(max_workers=min(os.cpu_count() or 1, len(sources) or 1)) as pool:
                return [
                    obj for objs in pool.map(lambda s: compile_serial([s], *args, **kwargs), sources) for obj in objs
                ]

        compiler.compile = compile_parallel
        try:
            super().build_extension(ext)
        finally:
            compiler.compile = compile_serial


class sdist(_sdist):
    """Stages the bclibc sources into the package for the time of the sdist, so the archive builds anywhere."""

    def run(self):
        _bclibc.stage()
        try:
            super().run()
        finally:
            _bclibc.unstage()


if cythonize is None:
    # `pip install --no-build-isolation --no-binary :all:` without Cython: skip the build on unsupported platforms
    setup()
    sys.exit(0)

options = {"bdist_wheel": {"py_limited_api": PY_LIMITED_API_TAG}} if USE_LIMITED_API else {}
setup(ext_modules=extensions(), cmdclass={"build_ext": build_ext, "sdist": sdist}, options=options)
