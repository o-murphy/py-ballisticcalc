#!/usr/bin/env python
"""Regenerate py_ballisticcalc_exts/_bcffi.pxd, the Cython declarations of bclibc_ffi.h (the C ABI of bclibc).

autopxd2 is a development dependency (``uv sync --group dev``); the generated file is committed, so building the package
does not need it. Run this after the bclibc submodule is bumped and commit the result; the test ``tests/test_bindings.py``
fails when the file is out of date. The header is read with BCLIBC_FFI_PARSE_ONLY (bclibc 2.2), which empties BCLIBC_API.

    python regenerate_bindings.py [--check]

``--check`` writes nothing: it exits non-zero when the committed file differs from what the current header gives.
"""

import difflib
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import _bclibc

OUT = HERE / "py_ballisticcalc_exts" / "_bcffi.pxd"
HEADER_RELATIVE = "include/bclibc/ffi/bclibc_ffi.h"
STUBS = HERE.parent / "py_ballisticcalc.ctypes" / "ctypesgen_stubs"  # stdint.h/stddef.h for a parser without a libc


def functions(text: str) -> set[str]:
    """The BCLIBCFFI_* functions a header (or a pxd) names."""
    return set(re.findall(r"\bBCLIBCFFI_[a-z0-9_]+", text))


def generate() -> str:
    header = _bclibc.bclibc_dir() / HEADER_RELATIVE
    script = Path(sys.executable).with_name("autopxd")
    command = [
        str(script) if script.exists() else (shutil.which("autopxd") or "autopxd"),
        "-q",
        "-D",
        "BCLIBC_FFI_PARSE_ONLY",
    ]
    if STUBS.is_dir():
        command += ["-I", str(STUBS)]
    done = subprocess.run([*command, str(header)], check=False, capture_output=True, text=True)
    if done.returncode != 0:
        sys.exit(f"autopxd failed ({done.returncode}):\n{done.stderr}")
    text = done.stdout
    # the header is found through the include path of the build (-I <bclibc>/include), not by the absolute path autopxd prints;
    # the block is nogil, or Cython refuses the calls inside `with nogil:` (the functions are noexcept for Cython 3 already)
    text, count = re.subn(
        r'cdef extern from "[^"]*bclibc_ffi\.h":', 'cdef extern from "bclibc/ffi/bclibc_ffi.h" nogil:', text
    )
    if count != 1:
        sys.exit("autopxd gave no `cdef extern from` block for bclibc_ffi.h")
    # names the header mentions in comments are not declarations: only the functions BCLIBC_API marks must all be there
    declared = set(re.findall(r"BCLIBC_API\s+[\w\s\*]+?\b(BCLIBCFFI_\w+)\s*\(", header.read_text()))
    lost = declared - functions(text)
    if lost:
        sys.exit(f"autopxd left out {len(lost)} functions of {header.name}: {sorted(lost)[:5]}")
    version = _bclibc.bclibc_version(_bclibc.bclibc_dir())[0]
    return (
        f"# Generated by regenerate_bindings.py (autopxd2) from bclibc_ffi.h of bclibc {version}. Do not edit.\n" + text
    )


def main(argv: list[str]) -> int:
    new = generate()
    if "--check" in argv:
        old = OUT.read_text() if OUT.exists() else ""
        if old == new:
            return 0
        sys.stdout.writelines(
            difflib.unified_diff(old.splitlines(True), new.splitlines(True), "committed", "regenerated", n=1)
        )
        return 1
    OUT.write_text(new)
    print(f"wrote {OUT.relative_to(HERE)}: {len(functions(new))} names")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
